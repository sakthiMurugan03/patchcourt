"use client";

import { Printer } from "lucide-react";
import { Button } from "@/components/ui/button";
import { VERDICT_META, type Debate, type Report } from "@/lib/types";

function escapeHtml(value: unknown): string {
  return String(value ?? "")
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&#39;");
}

function renderDebate(debate: Debate): string {
  const rows: string[] = [
    "<section class=\"debate\">",
    `<h3>${escapeHtml(debate.file)} — ${escapeHtml(debate.issue)}</h3>`,
  ];
  if (debate.verdict_summary) {
    rows.push(
      `<p class="verdict"><strong>Verdict:</strong> ${escapeHtml(debate.verdict_summary)}</p>`,
    );
  }
  rows.push(
    '<div class="cols">',
    `<div class="col"><h4>Prosecution</h4><p>${escapeHtml(debate.supporting) || "—"}</p></div>`,
    `<div class="col"><h4>Defense</h4><p>${escapeHtml(debate.opposing) || "—"}</p></div>`,
    "</div>",
  );
  if (debate.code_snippet) {
    rows.push(`<pre>${escapeHtml(debate.code_snippet)}</pre>`);
  }
  rows.push("</section>");
  return rows.join("");
}

function renderFindings(report: Report): string {
  const findings = report.finding_assessments ?? [];
  if (findings.length === 0) {
    return '<p class="muted">No adjudicated findings recorded.</p>';
  }
  const items = findings
    .map(
      (finding) =>
        `<li><code>${escapeHtml(finding.file)}:${escapeHtml(finding.line)}</code> ` +
        `<strong>[${escapeHtml(finding.category)}]</strong> ${escapeHtml(finding.message)} ` +
        `<em>(${escapeHtml(finding.status)}, ${escapeHtml(finding.contextual_action)})</em></li>`,
    )
    .join("");
  return `<ul class="findings">${items}</ul>`;
}

export function buildReportHtml(report: Report): string {
  const meta = VERDICT_META[report.verdict];
  const summary = report.contextual_summary ?? {};
  const debates = report.debate_transcripts ?? [];

  return `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8" />
<title>PatchCourt report — ${escapeHtml(report.pr_url)}</title>
<style>
  :root { color-scheme: light; }
  * { box-sizing: border-box; }
  body { font-family: -apple-system, BlinkMacSystemFont, "Segoe UI", Roboto, sans-serif; margin: 40px; color: #0f172a; }
  h1 { font-size: 22px; margin: 0 0 4px; }
  h2 { font-size: 16px; margin: 28px 0 10px; border-bottom: 1px solid #e2e8f0; padding-bottom: 6px; }
  h3 { font-size: 14px; margin: 0 0 6px; }
  h4 { font-size: 12px; text-transform: uppercase; letter-spacing: .04em; margin: 0 0 4px; color: #475569; }
  p { margin: 4px 0; line-height: 1.5; }
  .header { display: flex; justify-content: space-between; align-items: flex-start; gap: 16px; }
  .score { font-size: 34px; font-weight: 700; font-variant-numeric: tabular-nums; }
  .verdict-badge { display: inline-block; padding: 3px 10px; border-radius: 999px; color: #fff; font-size: 12px; font-weight: 600; }
  .muted { color: #64748b; font-size: 12px; }
  .summary { margin-top: 12px; font-size: 13px; color: #334155; }
  .debate { border: 1px solid #e2e8f0; border-radius: 10px; padding: 14px; margin-bottom: 14px; page-break-inside: avoid; }
  .verdict { background: #f1f5f9; border-radius: 6px; padding: 8px 10px; }
  .cols { display: grid; grid-template-columns: 1fr 1fr; gap: 12px; margin-top: 8px; }
  .col { background: #f8fafc; border-radius: 6px; padding: 8px 10px; font-size: 13px; }
  pre { background: #0f172a; color: #e2e8f0; border-radius: 6px; padding: 10px; overflow-x: auto; font-size: 12px; margin-top: 8px; }
  code { font-family: ui-monospace, SFMono-Regular, Menlo, monospace; font-size: 12px; }
  ul.findings { padding-left: 18px; }
  ul.findings li { margin-bottom: 6px; font-size: 13px; }
  footer { margin-top: 30px; border-top: 1px solid #e2e8f0; padding-top: 10px; font-size: 11px; color: #94a3b8; }
</style>
</head>
<body>
  <div class="header">
    <div>
      <h1>PatchCourt review report</h1>
      <p class="muted">${escapeHtml(report.pr_url)}</p>
    </div>
    <div style="text-align:right">
      <span class="verdict-badge" style="background:${escapeHtml(meta.color)}">${escapeHtml(meta.label)}</span>
      <p class="score" style="color:${escapeHtml(meta.color)}">${escapeHtml(report.overall_score.toFixed(1))}</p>
      <p class="muted">risk score (higher = riskier)</p>
    </div>
  </div>

  <p class="summary">
    ${escapeHtml(meta.blurb)}. ${escapeHtml(summary.total ?? report.claims.length)} finding(s) adjudicated${
      summary.blocking ? `, ${escapeHtml(summary.blocking)} blocking` : ""
    }.
  </p>

  <h2>Adjudicated findings</h2>
  ${renderFindings(report)}

  <h2>Courtroom debate</h2>
  ${debates.length ? debates.map(renderDebate).join("") : '<p class="muted">No debate rounds recorded.</p>'}

  <footer>Generated by PatchCourt — multi-agent code review with evidence-tiered adjudication.</footer>
</body>
</html>`;
}

export function ExportPdfButton({
  report,
  className,
}: {
  report: Report;
  className?: string;
}) {
  const handlePrint = () => {
    const printWindow = window.open("", "_blank", "width=900,height=1200");
    if (!printWindow) {
      return;
    }
    printWindow.document.open();
    printWindow.document.write(buildReportHtml(report));
    printWindow.document.close();
    printWindow.focus();
    // Give the browser a tick to lay out before opening the print dialog.
    window.setTimeout(() => printWindow.print(), 250);
  };

  return (
    <Button type="button" variant="outline" size="sm" className={className} onClick={handlePrint}>
      <Printer /> Export PDF
    </Button>
  );
}
